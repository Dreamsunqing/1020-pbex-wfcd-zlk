import { _electron as electron, expect as baseExpect } from '@playwright/test';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
const expect = baseExpect.configure({ timeout: 30000 });
const root = process.cwd(), output = path.resolve('artifacts/void-storm'), profile = await fs.mkdtemp(path.join(os.tmpdir(), 'wb-storm-ui-'));
await fs.mkdir(output, { recursive: true });
const env = { ...process.env, WORKBENCH_ROOT: root, WORKBENCH_USER_DATA: profile }; delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  const executablePath = process.env.WORKBENCH_TEST_EXECUTABLE;
  app = await electron.launch({ ...(executablePath ? { executablePath, args: [] } : { args: [root] }), env, timeout: 60000 });
  const page = await app.firstWindow(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => window.smokeReady, null, { timeout: 60000 });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('[data-panel=oracle]').click();
  await page.locator('[data-lab=void-storm-lab]').click();
  await page.locator('#storm-history').click();
  await expect(page.locator('.storm-overview')).toContainText('历史演示');
  await expect(page.locator('[data-storm-window]')).toHaveCount(24);
  await expect(page.locator('.storm-accuracy')).toContainText('75 / 75');
  await expect(page.locator('.storm-accuracy')).toContainText('暂无可核验样本');
  await expect(page.locator('.storm-schedule')).not.toContainText('CrewBattleNode');
  await expect(page.locator('.storm-content')).toContainText('76 / 450');
  await expect(page.locator('.storm-content')).toContainText('226 / 450');
  await expect(page.locator('.storm-candidate-card')).toHaveCount(4);
  await expect(page.locator('.storm-candidate-grid')).toContainText('爆发');
  await expect(page.locator('.storm-schedule')).toContainText('纪元候选');
  await expect(page.locator('#storm-copy')).toBeEnabled();
  await page.locator('#theme-select').selectOption('light');
  await page.screenshot({ path: path.join(output, 'de-light.png') });
  await page.locator('.storm-content').screenshot({ path: path.join(output, 'de-content.png') });
  await page.locator('#storm-server').selectOption('wg');
  await expect(page.locator('[data-storm-window]')).toHaveCount(48);
  await expect(page.locator('.storm-accuracy')).toContainText('163 / 163');
  await expect(page.locator('.storm-overview')).toContainText(':40');
  await expect(page.locator('.storm-content')).toContainText('101 / 476');
  await expect(page.locator('.storm-candidate-card')).toHaveCount(6);
  await page.locator('#theme-select').selectOption('dark');
  await page.screenshot({ path: path.join(output, 'wg-dark.png') });
  await page.locator('.storm-accuracy .storm-evaluations summary').click();
  await expect(page.locator('.storm-accuracy .storm-evaluations table tr')).toHaveCount(164);
  await page.locator('.storm-content-evaluations summary').click();
  await expect(page.locator('.storm-content-evaluations table tr')).toHaveCount(477);
  await page.locator('#storm-at').fill('2026-10-23T09:00');
  await page.locator('#storm-recalculate').click();
  await expect(page.locator('#storm-result')).toContainText('不能早于');
  await expect(page.locator('#storm-copy')).toBeDisabled();
  await page.locator('#storm-history').click();
  await expect(page.locator('[data-storm-window]')).toHaveCount(48);
  await page.setViewportSize({ width: 850, height: 1000 });
  await expect(page.locator('#void-storm-lab')).toBeVisible();
  expect(await page.locator('#void-storm-lab').evaluate(node => node.scrollWidth <= node.clientWidth + 2)).toBe(true);
  await page.screenshot({ path: path.join(output, 'wg-narrow.png') });
  expect(errors).toEqual([]);
  const reportPath = path.resolve('输出/九重天风暴预测/九重天风暴预测.html');
  if (await fs.stat(reportPath).then(() => true, () => false)) {
    const opened = app.waitForEvent('window');
    await app.evaluate(async ({ BrowserWindow }, file) => { const win = new BrowserWindow({ show: false, width: 1280, height: 1000 }); await win.loadFile(file); }, reportPath);
    const report = await opened;
    await expect(report.locator('[data-storm-window]')).toHaveCount(24);
    await report.getByRole('button', { name: '国服', exact: true }).click();
    await expect(report.locator('[data-storm-window]')).toHaveCount(48);
    await expect(report.locator('.storm-schedule')).toContainText('尚未验证');
    await report.screenshot({ path: path.join(output, 'standalone-report.png') });
  }
  console.log(JSON.stringify({ ok: true, executablePath: executablePath || 'development', checks: ['DE24窗口75/75及76/450节点命中', 'WG48窗口163/163及101/476节点命中', '逐波次和逐任务证据展开', '前三节点与类型候选', '错误后复制禁用', '明暗及窄屏无溢出', '无页面异常'], output }));
} finally {
  await app?.close(); await fs.rm(profile, { recursive: true, force: true });
}
