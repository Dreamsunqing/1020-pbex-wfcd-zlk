// JSON remains the editable source. Browsers import the generated JS module without a JSON fetch.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
export async function prepareInlineTokens({ check = false } = {}) {
  const read = name => fs.readFile(path.join(root, 'src/data', name), 'utf8').then(JSON.parse);
  const registry = await read('inline-tokens.json');
  const assets = await read('text-icon-assets.json');
  for (const [token, asset] of Object.entries(assets.tokens)) {
    if (registry.entries[token] && registry.entries[token].kind !== 'icon') continue;
    registry.entries[token] = { kind: 'icon', label: `<${token}>`, ...registry.entries[token], image: asset.file };
  }
  // Explicit alias: DT_HEAT uses the same damage type as DT_FIRE, never a filename guess.
  if (registry.entries.DT_FIRE?.image) registry.entries.DT_HEAT.image = registry.entries.DT_FIRE.image;
  const content = '// Generated by scripts/prepare-inline-tokens.mjs; edit inline-tokens.json instead.\nexport default ' + JSON.stringify(registry, null, 2) + ';\n';
  const target = path.join(root, 'src/data/inline-tokens.generated.mjs');
  if (check) { if (await fs.readFile(target, 'utf8') !== content) throw new Error('文本图标运行时登记表未更新：node scripts/prepare-inline-tokens.mjs'); }
  else await fs.writeFile(target, content);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await prepareInlineTokens({ check: process.argv.includes('--check') });
