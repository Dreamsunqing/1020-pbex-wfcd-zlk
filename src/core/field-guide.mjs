export function describeField(key, path = '', file = '') {
  if (key === '[]' || key === '{key}' || key === '$') return { key, label: key === '$' ? '文档根节点' : key === '[]' ? '数组元素' : '动态键条目', description: key === '{key}' ? '将同类动态键合并为一个结构；所有条目仍参与扫描，可查看实际键样例。' : '此结构来自当前 JSON 的完整扫描；子字段合并所有实际记录。', status: 'structural', source: '当前 JSON 结构' };
  const definition = definitions.get(key);
  if (key === 'impact' && /behaviours/.test(path)) return { key, label: '命中伤害配置', description: '弹丸或武器命中时的伤害分量集合；此对象不是单一冲击伤害数值。', status: 'documented', source: 'Plus ExportWeapons.json · behaviours' };
  if (key === 'energy' && /(?:colors?|ColorMap)(?:"\]|\.|\/|\[)/i.test(path)) return { key, label: '能量配色', description: '配色对象中的能量颜色通道，不是战甲能量容量。', status: 'documented', source: 'WFCD index.d.ts · ColorMap' };
  if ((key === 'name' || key === 'date') && /patchlogs?|changelog|introduced/i.test(path)) return { key, label: key === 'name' ? '更新版本名称' : '更新日期', description: key === 'name' ? '该更新或首次加入版本的名称。' : '该更新或首次加入版本的发布日期，保留原始时区。', status: 'documented', source: 'WFCD index.d.ts · PatchLog / Update' };
  if (!definition && /^Export[A-Z]/.test(key)) return { key, label: '官方导出记录集合', description: `${key} 对应类别的全部记录；子结构合并当前文件中的全部元素。`, status: 'structural', source: '官方 Manifest 集合键' };
  if (!definition) return { key, label: key, description: '尚未维护此字段的中文业务释义；下方类型、子字段及样例来自当前 JSON，可用于后续补充映射。', status: 'unknown', source: '待核对上游定义' };
  return { key, ...definition, status: 'documented', source: ['criticalChance', 'criticalMultiplier', 'omegaAttenuation', 'disposition', 'power', 'patchlogs', 'introduced'].includes(key) ? 'WFCD index.d.ts / Plus 导出字段' : ['crit_chance', 'crit_mult', 'status_chance'].includes(key) ? 'WFCD build/wikia/transformers/transformWeapon.ts' : '工作台字段说明（结合当前来源使用）', file };
}

export function displayMeaning(value, guide) {
  if (typeof value !== 'number' || !Number.isFinite(value)) return '';
  const readable = number => Number(number.toPrecision(7)).toLocaleString('zh-CN', { maximumFractionDigits: 6 });
  if (guide.format === 'ratio') return `${readable(value * 100)}%`;
  if (guide.format === 'percent') return `${readable(value)}%`;
  if (guide.format === 'multiplier') return `${readable(value)} 倍`;
  if (guide.format === 'coefficient') return readable(value);
  return '';
}
